// Generates src/ui/icons.ts from the remixicon package: only the icons the
// prototype uses, as inline path data, so no SVG files load at runtime.
// Run with `bun scripts/icons.ts` after adding a name below.
import { Glob } from 'bun';

const names = `
add-line arrow-up-line arrow-right-line arrow-left-line arrow-down-s-line arrow-right-s-line arrow-up-s-line
arrow-up-circle-fill arrow-down-circle-fill indeterminate-circle-fill attachment-2 sparkling-line sparkling-2-fill
infinity-line stop-fill check-line file-copy-line close-line menu-line search-line settings-4-line settings-6-line
side-bar-fill home-line chat-ai-line customer-service-line folder-3-line folder-open-line file-line file-code-line
information-fill checkbox-circle-fill error-warning-fill notification-3-fill terminal-box-line git-branch-line
git-merge-line git-pull-request-line code-s-slash-line delete-bin-line edit-line more-2-line more-line download-line
share-line coins-fill group-line timer-line cpu-line robot-2-line brain-line loader-4-line palette-line plug-line
database-2-line tools-fill school-line store-2-line bank-card-line organization-chart settings-line code-block
book-open-line sun-line moon-line computer-line eye-line file-search-line file-edit-line pencil-line play-line
chat-3-line mic-line at-line question-line list-check-3 task-line user-line logout-box-r-line expand-up-down-line
sidebar-fold-line sidebar-unfold-line mail-line lock-line alert-line time-line history-line chat-new-line
edit-box-line cup-line stack-line flask-line global-line bug-line checkbox-blank-circle-line
checkbox-circle-line close-circle-fill error-warning-line pause-circle-line bold italic link heart-line
bookmark-line align-left filter-3-line upload-2-line image-line star-fill star-line hashtag dashboard-line
`
  .trim()
  .split(/\s+/);

const found = new Map<string, string>();
for await (const file of new Glob('node_modules/remixicon/icons/*/*.svg').scan(
  '.',
)) {
  const name = file.split('/').pop()!.replace('.svg', '');
  if (names.includes(name)) found.set(name, await Bun.file(file).text());
}

const missing = names.filter((n) => !found.has(n));
if (missing.length) throw new Error(`Missing icons: ${missing.join(', ')}`);

const pascal = (n: string) =>
  'Ri' + n.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());

const lines = [...found.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, svg]) => {
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
    return `export const ${pascal(name)} = icon(${JSON.stringify(inner)});`;
  });

await Bun.write(
  'src/ui/icons.ts',
  `// Generated by scripts/icons.ts from the remixicon package (Remix Icon License v1.0).\n` +
    `import { icon } from './icon';\n\n${lines.join('\n')}\n`,
);
console.log(`${found.size} icons`);
